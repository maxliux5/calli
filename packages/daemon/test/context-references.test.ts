import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, symlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { AddressInfo } from 'node:net';
import { AgentRegistry } from '../src/agents.js';
import { AttachmentStore } from '../src/attachments.js';
import { BorrowingService } from '../src/borrowing.js';
import { borrowingServer } from '../src/borrowing-server.js';
import { createHttpServer, listenPrivate } from '../src/http.js';
import { Store } from '../src/store.js';
import { ThreadManager } from '../src/threads.js';
import { sessionEnvironment } from '../src/adapters/types.js';

const here = dirname(fileURLToPath(import.meta.url));
const wire = (reference: unknown) => `<calli-references>\n${JSON.stringify([reference])}\n</calli-references>\n\nCompare the discussion.`;

test('reference API and CLI: explicit scope, fixed history, pagination, long answers and missing sources', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'calli-references-'));
  const registry = new AgentRegistry([{ id: 'pi', adapter: 'pi', label: 'pi', command: [process.execPath, join(here, 'fixtures/fake-pi.mjs')] }], null);
  const store = new Store(join(dir, 'data'));
  const manager = new ThreadManager(store, registry.adapters, [dir], new AttachmentStore(dir));
  const socket = join(dir, 'tools.sock');
  const tools = new BorrowingService(store, manager, registry.adapters, dir, socket);
  const ipc = borrowingServer(tools);
  const server = createHttpServer({ manager, token: 'references-test-token', webDir: null, version: 'test' });
  await listenPrivate(ipc, socket);
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
  const post = (body: unknown, auth = true) => fetch(base + '/api/context-references', { method: 'POST', headers: { 'Content-Type': 'application/json', ...(auth ? { Authorization: 'Bearer references-test-token' } : {}) }, body: JSON.stringify(body) });
  try {
    const source = await manager.createThread({ agent: 'pi', cwd: dir, title: 'Design discussion' });
    const recipient = await manager.createThread({ agent: 'pi', cwd: dir });
    const other = await manager.createThread({ agent: 'pi', cwd: dir });
    const long = '字😀'.repeat(10000);
    for (let i = 0; i < 3; i++) {
      store.appendEvent(source.id, `turn-${i}`, 'turn.started', { text: `question ${i}` });
      store.appendEvent(source.id, `turn-${i}`, 'message.delta', { text: i === 2 ? long : `answer ${i}` });
      store.appendEvent(source.id, `turn-${i}`, 'tool.start', { id: `tool-${i}`, title: 'Read', input: 'large tool payload'.repeat(10000) });
      store.appendEvent(source.id, `turn-${i}`, 'turn.done', {});
    }
    for (let i = 0; i < 55; i++) store.appendEvent(source.id, 'turn-2', 'tool.start', { id: `extra-${i}`, title: 'Read' });
    const snapshot = store.listEvents(source.id, 0, -1);
    assert.equal((await post({ kind: 'thread', sourceId: source.id }, false)).status, 401);
    assert.equal((await post({ kind: 'thread', sourceId: 'missing' })).status, 404);
    assert.equal((await post({ kind: 'other' })).status, 400);
    const response = await post({ kind: 'thread', sourceId: source.id });
    assert.equal(response.status, 201);
    const reference = await response.json();
    assert.equal(reference.title, 'Design discussion');
    assert.ok(!JSON.stringify(reference).includes('question'));
    assert.throws(() => manager.references.read(recipient.id, { id: reference.id }), /not attached/);
    assert.throws(() => manager.references.prepare(recipient.id, wire(reference), false), /cannot read/);
    const prepared = manager.references.prepare(recipient.id, wire(reference), true);
    assert.match(prepared.text, /calli references/);
    assert.throws(() => manager.references.read(recipient.id, { id: reference.id }), /not attached/, 'validation does not grant a rejected send');
    manager.references.grant(recipient.id, prepared.references);
    const env = tools.environment(recipient.id)!;
    const cli = (...args: string[]) => new Promise<any>((resolve, reject) => execFile(process.execPath, [join(here, '../bin/calli'), 'references', reference.id, ...args], { env: sessionEnvironment({}, env) }, (err, stdout, stderr) => err ? reject(new Error(stderr)) : resolve(JSON.parse(stdout))));
    store.appendEvent(source.id, 'turn-new', 'turn.started', { text: 'must not enter the snapshot' });
    store.appendEvent(source.id, 'turn-2', 'message.delta', { text: 'late text' });
    const page = await cli('--turns', '1');
    assert.equal(page.turns.length, 1);
    assert.equal(page.turns[0].question, 'question 2');
    assert.equal(page.turns[0].answer.truncated, true);
    assert.ok(page.command.includes('--before'));
    assert.ok(!JSON.stringify(page).includes('large tool payload'));
    assert.match(page.turns[0].toolsCommand, /--tools/);
    const toolIndex = await cli('--tools', 'turn-2');
    const nextTools = await cli('--tools', 'turn-2', '--offset', String(toolIndex.nextOffset));
    assert.equal(toolIndex.tools.length + nextTools.tools.length, 56);
    assert.equal(nextTools.command, null);
    const tool = await cli('--turn', 'turn-2', '--tool', 'tool-2');
    assert.match(tool.text, /large tool payload/);
    assert.ok(tool.command.includes('--tool'));
    const older = await cli('--before', String(page.nextCursor));
    assert.deepEqual(older.turns.map((v: any) => v.question), ['question 0', 'question 1']);
    const first = await cli('--turn', 'turn-2');
    const second = await cli('--turn', 'turn-2', '--offset', String(first.nextOffset));
    assert.equal(first.text + second.text, long);
    assert.equal(second.command, null);
    assert.throws(() => manager.references.read(other.id, { id: reference.id }), /not attached/);
    assert.throws(() => manager.references.read(recipient.id, { id: reference.id, turn: 'turn-new' }), /snapshot/);
    assert.throws(() => manager.references.read(recipient.id, { id: reference.id, turns: 51 }), /pagination/);
    assert.throws(() => manager.references.read(recipient.id, { id: reference.id, offset: 1 }), /requires/);
    assert.deepEqual(store.listEvents(source.id, 0, -1).slice(0, snapshot.length), snapshot);
    assert.equal(manager.getThread(source.id).agentSessionId, null);
    const folder = join(dir, 'folder with spaces'); mkdirSync(folder);
    const directory = await (await post({ kind: 'directory', path: folder })).json();
    assert.equal(directory.path, folder);
    const combined = manager.references.prepare(recipient.id, wire(reference) + '\n\n' + wire(directory), true);
    assert.deepEqual(combined.references.map(item => item.id), [reference.id, directory.id]);
    assert.equal(manager.references.prepare(recipient.id, wire(reference) + '\n\n' + wire(reference), true).references.length, 1);
    const snapshotResponse = await post({ kind: 'message', title: 'Selected reply', path: 'other-machine/project', text: long, sourceId: 'not-a-local-thread', turnId: 'external-turn' });
    assert.equal(snapshotResponse.status, 201);
    const message = await snapshotResponse.json();
    assert.ok(!JSON.stringify(message).includes(long.slice(0, 100)), 'the browser gets metadata, not a duplicate message body');
    assert.throws(() => manager.references.read(recipient.id, { id: message.id }), /not attached/);
    manager.references.grant(recipient.id, manager.references.prepare(recipient.id, wire(message), true).references);
    const messageFirst = manager.references.read(recipient.id, { id: message.id }) as { text: string; nextOffset: number };
    const messageSecond = manager.references.read(recipient.id, { id: message.id, offset: messageFirst.nextOffset }) as { text: string };
    assert.equal(messageFirst.text + messageSecond.text, long);
    assert.throws(() => manager.references.read(recipient.id, { id: message.id, turn: 'external-turn' }), /only accepts/);
    assert.throws(() => manager.references.read(other.id, { id: message.id }), /not attached/);
    assert.equal((await post({ kind: 'message', title: 'Empty', path: '', text: '' })).status, 400);
    assert.equal(manager.getThread(recipient.id).cwd, dir);
    assert.equal((await post({ kind: 'directory', path: '/etc' })).status, 403);
    symlinkSync('/etc', join(dir, 'outside'));
    assert.equal((await post({ kind: 'directory', path: join(dir, 'outside') })).status, 403);
    store.appendEvent(source.id, null, 'thread.historyChanged', {});
    assert.throws(() => manager.references.read(recipient.id, { id: reference.id }), /history changed/);
    store.db.prepare('DELETE FROM threads WHERE id=?').run(source.id);
    assert.throws(() => manager.references.read(recipient.id, { id: reference.id }), /not found/);
  } finally {
    await tools.dispose(); await manager.shutdown();
    await Promise.all([new Promise<void>(resolve => server.close(() => resolve())), new Promise<void>(resolve => ipc.close(() => resolve()))]);
    store.close(); rmSync(dir, { recursive: true, force: true });
  }
});
